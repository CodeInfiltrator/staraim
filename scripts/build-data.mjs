/**
 * Builds the embedded sky catalogue for Staraim from the public
 * d3-celestial dataset (BSD-3-Clause) — https://github.com/ofrohn/d3-celestial
 *
 * Output: plain TypeScript modules under src/lib/astro/data
 *   Run with: node scripts/build-data.mjs <path-to-d3-celestial/data>
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const SRC = process.argv[2];
const OUT = join(process.cwd(), "src/lib/astro/data");

if (!SRC) {
  console.error("usage: node scripts/build-data.mjs <d3-celestial/data dir>");
  process.exit(1);
}

mkdirSync(OUT, { recursive: true });

const read = (f) => JSON.parse(readFileSync(join(SRC, f), "utf8"));
const r2 = (n, p = 2) => Number(Number(n).toFixed(p));
const r3 = (n) => Number(Number(n).toFixed(3));

/* ------------------------------------------------------------------ stars */
const starsRaw = read("stars.6.json").features;
const names = read("starnames.json");

// Keep everything a naked eye could plausibly see.
const MAG_LIMIT = 5.2;
const stars = starsRaw
  .filter((f) => f.properties.mag <= MAG_LIMIT)
  .map((f) => {
    const hip = String(f.id);
    const meta = names[hip] ?? {};
    const bv = parseFloat(f.properties.bv);
    return {
      ra: r2(f.geometry.coordinates[0]),
      dec: r2(f.geometry.coordinates[1]),
      mag: r2(f.properties.mag),
      bv: Number.isFinite(bv) ? r2(bv) : 0,
      name: meta.name || "",
      bayer: meta.bayer || "",
      con: meta.c || "",
    };
  })
  .sort((a, b) => a.mag - b.mag);

// Parallel flat arrays: object literals would triple the payload in key names.
const starRa = stars.map((s) => s.ra);
const starDec = stars.map((s) => s.dec);
const starMag = stars.map((s) => s.mag);
const starBv = stars.map((s) => s.bv);

// Named stars are the ones worth surfacing in the UI.
const named = stars
  .filter((s) => s.name)
  .map((s) => ({
    n: s.name,
    ra: s.ra,
    dec: s.dec,
    m: s.mag,
    c: s.con,
    b: s.bayer,
  }));

writeFileSync(
  join(OUT, "stars.ts"),
  `// GENERATED by scripts/build-data.mjs — do not edit by hand.
// Source: d3-celestial stars.6.json (HYG/BSC derived), mag <= ${MAG_LIMIT}.
//
// ra  : right ascension in degrees [0..360)
// dec : declination in degrees [-90..90]
// mag : visual magnitude (lower = brighter)
// bv  : B-V colour index, used to derive the rendered star colour
export interface StarDatum {
  ra: number;
  dec: number;
  mag: number;
  bv: number;
}

export const STAR_RA: number[] = ${JSON.stringify(starRa)};
export const STAR_DEC: number[] = ${JSON.stringify(starDec)};
export const STAR_MAG: number[] = ${JSON.stringify(starMag)};
export const STAR_BV: number[] = ${JSON.stringify(starBv)};
export const STAR_COUNT = ${stars.length};

export interface NamedStar {
  n: string;
  ra: number;
  dec: number;
  m: number;
  c: string;
  b: string;
}

export const NAMED_STARS: NamedStar[] = ${JSON.stringify(named)};
`,
);

/* --------------------------------------------------------- constellations */
const linesRaw = read("constellations.lines.json").features;
const metaRaw = read("constellations.json").features;
const metaById = new Map(metaRaw.map((f) => [f.id, f.properties]));

const lines = linesRaw.map((f) => ({
  id: f.id,
  name: metaById.get(f.id)?.en ?? f.id,
  gen: metaById.get(f.id)?.gen ?? "",
  rank: Number(metaById.get(f.id)?.rank ?? 3),
  segs: f.geometry.coordinates.map((seg) => seg.map(([ra, dec]) => [r3(ra), r3(dec)])),
}));

// Label anchor = centroid of the figure's own vertices.
const withCentroid = lines.map((c) => {
  let x = 0;
  let y = 0;
  let z = 0;
  let n = 0;
  for (const seg of c.segs)
    for (const [ra, dec] of seg) {
      const a = (ra * Math.PI) / 180;
      const d = (dec * Math.PI) / 180;
      x += Math.cos(d) * Math.cos(a);
      y += Math.cos(d) * Math.sin(a);
      z += Math.sin(d);
      n++;
    }
  x /= n;
  y /= n;
  z /= n;
  const ra = (((Math.atan2(y, x) * 180) / Math.PI) + 360) % 360;
  const dec = (Math.asin(Math.max(-1, Math.min(1, z))) * 180) / Math.PI;
  return { ...c, ra: r3(ra), dec: r3(dec) };
});

writeFileSync(
  join(OUT, "constellations.ts"),
  `// GENERATED by scripts/build-data.mjs — do not edit by hand.
// Source: d3-celestial constellations.lines.json (IAU stick figures).
export interface ConstellationFigure {
  id: string;
  name: string;
  gen: string;
  rank: number;
  /** [raDeg, decDeg] vertex chains. */
  segs: [number, number][][];
  /** Centroid used to anchor the on-screen label. */
  ra: number;
  dec: number;
}

export const CONSTELLATIONS: ConstellationFigure[] = ${JSON.stringify(withCentroid)};
`,
);

/* ------------------------------------------------------------------- DSOs */
const dsoTypes = {
  oc: "Open cluster",
  gc: "Globular cluster",
  neb: "Nebula",
  pn: "Planetary nebula",
  gx: "Galaxy",
  snr: "Supernova remnant",
  dn: "Dark nebula",
  mw: "Milky Way patch",
  cg: "Cluster of galaxies",
  ast: "Asterism",
};

const messier = read("messier.json").features.map((f) => ({
  id: f.properties.name,
  desig: f.properties.desig,
  name: f.properties.alt || f.properties.name,
  type: dsoTypes[f.properties.type] ?? "Deep sky object",
  rawType: f.properties.type,
  mag: Number(f.properties.mag) || 0,
  dim: f.properties.dim || "",
  ra: r3(f.geometry.coordinates[0]),
  dec: r3(f.geometry.coordinates[1]),
  con: (f.properties.cl || "").trim(),
}));

const bright = read("dsos.bright.json").features
  .filter((f) => Number(f.properties.mag) <= 8)
  .map((f) => ({
    id: f.properties.desig,
    desig: f.properties.desig,
    name: f.properties.desig,
    type: dsoTypes[f.properties.type] ?? "Deep sky object",
    rawType: f.properties.type,
    mag: Number(f.properties.mag) || 0,
    dim: f.properties.dim || "",
    ra: r3(f.geometry.coordinates[0]),
    dec: r3(f.geometry.coordinates[1]),
    con: "",
  }));

const seen = new Set(messier.map((d) => d.desig));
const dso = [...messier, ...bright.filter((d) => !seen.has(d.desig))].sort(
  (a, b) => a.mag - b.mag,
);

writeFileSync(
  join(OUT, "dso.ts"),
  `// GENERATED by scripts/build-data.mjs — do not edit by hand.
// Source: d3-celestial messier.json + dsos.bright.json
export interface DsoDatum {
  id: string;
  desig: string;
  name: string;
  type: string;
  rawType: string;
  mag: number;
  dim: string;
  ra: number;
  dec: number;
  con: string;
}

export const DSO: DsoDatum[] = ${JSON.stringify(dso)};
`,
);

const kb = (p) => (readFileSync(join(OUT, p)).length / 1024).toFixed(1);
console.log(
  `stars      ${stars.length} (${named.length} named)  ${kb("stars.ts")} KB`,
);
console.log(`constell.  ${withCentroid.length} figures        ${kb("constellations.ts")} KB`);
console.log(`dso        ${dso.length} objects       ${kb("dso.ts")} KB`);
