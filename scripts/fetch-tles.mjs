/**
 * Fetches two line element sets from Celestrak and writes them into the
 * project as a static module, so the sky map keeps working offline.
 *
 *   node scripts/fetch-tles.mjs
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const OUT = join(process.cwd(), "src/lib/astro/data");
mkdirSync(OUT, { recursive: true });

/** Satellite NORAD ids we want to show. */
const CATALOGS = [
  { id: "25544", kind: "Space station" },
  { id: "20580", kind: "Space telescope" },
  { id: "48274", kind: "Space station" },
  { id: "33591", kind: "Weather satellite" },
  { id: "37853", kind: "Weather satellite" },
];

/** Fetch the first `count` members of a Celestrak group. */
async function fetchGroup(group, count) {
  const url = `https://celestrak.org/NORAD/elements/gp.php?GROUP=${group}&FORMAT=tle`;
  const res = await fetch(url, { headers: { "User-Agent": "Staraim/1.0" } });
  if (!res.ok) throw new Error(`${group}: HTTP ${res.status}`);
  const lines = (await res.text()).trim().split(/\r?\n/).filter((l) => l.trim());
  const out = [];
  for (let i = 0; i + 2 < lines.length && out.length < count; i += 3) {
    out.push({
      name: lines[i].trim(),
      line1: lines[i + 1].trim(),
      line2: lines[i + 2].trim(),
    });
  }
  return out;
}

const fmt = (v) => String(v).padStart(2, "0");

async function fetchTle(catnr) {
  const url = `https://celestrak.org/NORAD/elements/gp.php?CATNR=${catnr}&FORMAT=tle`;
  const res = await fetch(url, { headers: { "User-Agent": "Staraim/1.0" } });
  if (!res.ok) throw new Error(`${catnr}: HTTP ${res.status}`);
  const text = (await res.text()).trim();
  const lines = text.split(/\r?\n/).filter((l) => l.trim().length);
  if (lines.length < 3) throw new Error(`${catnr}: unexpected response`);
  return { name: lines[0].trim(), line1: lines[1].trim(), line2: lines[2].trim() };
}

const tles = [];
for (const c of CATALOGS) {
  try {
    const tle = await fetchTle(c.id);
    tles.push({ id: c.id, label: tle.name, kind: c.kind, ...tle });
    console.log(`ok   ${c.id} ${tle.name}`);
  } catch (err) {
    console.warn(`skip ${c.id}: ${err.message}`);
  }
}

// A handful of Starlink satellites, spread across the shell.
try {
  const starlinks = await fetchGroup("starlink", 6);
  starlinks.forEach((s, i) => {
    tles.push({ id: `sl-${i}`, label: s.name, kind: "Satellite", ...s });
  });
  console.log(`ok   starlink x${starlinks.length}`);
} catch (err) {
  console.warn(`skip starlink: ${err.message}`);
}

const payload = tles.map((t) => ({
  id: t.id,
  label: t.label,
  kind: t.kind,
  name: t.name,
  line1: t.line1,
  line2: t.line2,
}));

writeFileSync(
  join(OUT, "satellites.ts"),
  `// GENERATED by scripts/fetch-tles.mjs — do not edit by hand.
// Source: Celestrak GP two line element sets.
export interface SatelliteTle {
  id: string;
  label: string;
  kind: string;
  name: string;
  line1: string;
  line2: string;
}

export const SATELLITES: SatelliteTle[] = ${JSON.stringify(payload)};
`,
);

console.log(`\n${payload.length} satellites -> src/lib/astro/data/satellites.ts`);
